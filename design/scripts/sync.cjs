// Synchronize prototype metadata and bundled documents from this repository.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
function sync() {
  const text = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  const version = text('Directory.Build.props').match(/<Version>([^<]+)<\/Version>/)[1];
  const website = text('Directory.Build.props').match(/<PackageProjectUrl>([^<]+)<\/PackageProjectUrl>/)[1];
  const packages = [...text('Directory.Packages.props').matchAll(/<PackageVersion Include="([^"]+)"/g)].map(m => m[1]);
  const project = {version, website, copyright:'Copyright © 2026 沙漠尽头的狼 / CodeWF', repository:'https://github.com/dotnet9/Vex', license:'MIT', components:packages};
  const documents = Object.fromEntries([
    ['thanks','鸣谢.md','docs/鸣谢.md'], ['changelog','更新日志.md','docs/更新日志.md']
  ].map(([key,name,file]) => [key,{name,file:'../'+file,text:text(file)}]));
  const out = (file, value) => {const target=path.join(root,'design',file);fs.mkdirSync(path.dirname(target),{recursive:true});if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==value)fs.writeFileSync(target,value,'utf8');};
  out('assets/project-info.js', '// Generated by design/scripts/sync.cjs.\nwindow.VexProject = '+JSON.stringify(project,null,2)+';\nif (window.VEX_DATA) Object.assign(VEX_DATA.metadata, {version: VexProject.version, copyright: VexProject.copyright});\ndocument.addEventListener("DOMContentLoaded", () => {\n  document.querySelectorAll("[data-project-components]").forEach(el => el.textContent = VexProject.components.join(" · "));\n  document.querySelectorAll("[data-project-website]").forEach(el => el.href = VexProject.website);\n});\n');
  out('assets/generated/documents-data.js', '// Generated by design/scripts/sync.cjs from this repository.\nwindow.VexDocuments = '+JSON.stringify(documents,null,2)+';\n');
  return version;
}
if (require.main === module) console.log('Prototype documents synchronized: Vex '+sync());
module.exports = sync;
