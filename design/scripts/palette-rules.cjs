/* 从 CodeWF.Avalonia《配色与排版令牌规则.md》附录 A 生成原型配色与密度令牌。
 * 单一事实源：规则文档。本脚本产出（均带版本戳，禁止手写，见规则 §14）：
 *   assets/palettes.css                          8 套配色 × 明暗 + 默认回退块
 *   assets/palettes.js                           VexPalettes 数据与旧 Key 别名
 *   assets/density.css                           密度三档显式值表（§6）
 *   assets/generated/palette-rules-data.js       供浏览器自定义配色编辑器使用
 * 用法：node scripts/palette-rules.cjs [--rules <规则文档路径>] [--check]（--check 只校验不落盘） */
const fs = require('node:fs');
const path = require('node:path');
const Rules = require('../assets/palette-rules.js');

const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const flag = name => args.indexOf(name);
const rulesPath = flag('--rules') >= 0 ? path.resolve(args[flag('--rules') + 1])
  : (process.env.VEX_RULES_DOC || 'D:/github/libs/CodeWF.Avalonia/docs/配色与排版令牌规则.md');
const libRoot = path.dirname(path.dirname(rulesPath));

const doc = fs.readFileSync(rulesPath, 'utf8');
const appendix = doc.slice(Math.max(doc.indexOf('## 附录 A'), 0));
const dataMatch = appendix.match(/```json\s*([\s\S]*?)```/);
if (!dataMatch) throw new Error('规则文档附录 A 中未找到 json 数据块: ' + rulesPath);
const data = JSON.parse(dataMatch[1]);

function libVersion() {
  try {
    const props = fs.readFileSync(path.join(libRoot, 'Directory.Build.props'), 'utf8');
    return props.match(/<Version>([^<]+)<\/Version>/)[1];
  } catch (_) { return 'unknown'; }
}
const version = libVersion();
const stamp = 'Generated by design/scripts/palette-rules.cjs · source: CodeWF.Avalonia '
  + version + ' docs/配色与排版令牌规则.md (ruleVersion ' + data.ruleVersion + '). Do not edit.';

/* 组装一套配色的完整基础色（状态四键缺省取全局默认，§1）。 */
function baseOf(palette, mode) {
  const light = palette[mode];
  return Object.assign({}, light, {
    danger: light.danger || data.statusDefaults[mode].danger,
    success: light.success || data.statusDefaults[mode].success,
    warning: light.warning || data.statusDefaults[mode].warning,
    info: light.info || data.statusDefaults[mode].info
  });
}

/* 8 色色卡（浅色态：纸面/面板/墨色/强调 + 四状态色）：输出颜色数组，UI 渲染为 8 个独立小圆圈。 */
function swatchOf(palette) {
  const base = baseOf(palette, 'light');
  return [base.paper, base.surface, base.ink, base.accent, base.danger, base.success, base.warning, base.info];
}

function cssBlock(mode, paletteKey, vars) {
  const body = Object.entries(vars).map(([key, value]) => '--' + key + ':' + value).join(';');
  return ':root[data-theme="' + mode + '"]' + (paletteKey ? '[data-palette="' + paletteKey + '"]' : '') + '{color-scheme:' + mode + ';' + body + '}';
}

const issues = [];
const paletteCss = [];
const paletteEntries = [];
for (const [key, palette] of Object.entries(data.palettes)) {
  const summary = { key, label: palette.label, en: palette.en, note: palette.note, recommended: !!palette.recommended, swatch: swatchOf(palette) };
  for (const mode of ['light', 'dark']) {
    const base = baseOf(palette, mode);
    const report = Rules.validate(base, mode, data.statusDefaults);
    report.forEach(message => issues.push(key + '/' + mode + ': ' + message));
    const vars = Rules.deriveVars(base, mode, data.derivation[mode]);
    paletteCss.push(cssBlock(mode, key, vars));
    if (mode === 'light') {
      Object.assign(summary, {
        light: base.accent, bg: vars.bg, paper: base.paper, panel: base.surface,
        fg: base.ink, muted: vars.muted
      });
    } else {
      Object.assign(summary, {
        dark: base.accent, darkBg: vars.bg, darkPaper: base.paper, darkPanel: base.surface,
        darkFg: base.ink, darkMuted: vars.muted
      });
    }
  }
  paletteEntries.push(summary);
}

/* 旧 Key → 新 Key 别名（自用迁移，规则 §2 替换声明）。 */
const legacyAliases = {
  weft: 'teal', aquatic: 'teal', teal: 'teal',
  ocean: 'indigo', blue: 'indigo', dusk: 'indigo', dotnet: 'indigo', 'night-sky': 'indigo', default: 'indigo',
  sand: 'amber', ochre: 'amber', desert: 'amber',
  rose: 'crimson', iris: 'violet', plum: 'violet', aurora: 'violet',
  olive: 'pine', ember: 'terracotta'
};

/* 密度三档 → CSS 变量（§6 显式值表；normal 作为 :root 基线）。 */
function densityVars(tier) {
  const d = data.density[tier];
  return {
    '--fs-caption': d.fontSize[0] + 'px', '--fs-body': d.fontSize[1] + 'px', '--fs-subtitle': d.fontSize[2] + 'px',
    '--fs-title': d.fontSize[3] + 'px', '--fs-display': d.fontSize[4] + 'px',
    '--control-h-sm': d.controlHeight[0] + 'px', '--control-h-md': d.controlHeight[1] + 'px', '--control-h-lg': d.controlHeight[2] + 'px',
    '--pad-sm': d.padding[0] + 'px', '--pad-md': d.padding[1] + 'px', '--pad-lg': d.padding[2] + 'px',
    '--gap-sm': d.gap[0] + 'px', '--gap-md': d.gap[1] + 'px', '--gap-lg': d.gap[2] + 'px',
    '--radius-sm': d.cornerRadius[0] + 'px', '--radius-md': d.cornerRadius[1] + 'px', '--radius-lg': d.cornerRadius[2] + 'px',
    '--row-h': d.listRowHeight + 'px', '--icon-size': d.iconSize + 'px'
  };
}
function densityBlock(selector, tier) {
  return selector + '{' + Object.entries(densityVars(tier)).map(([k, v]) => k + ':' + v).join(';') + '}';
}
const densityCss = '/* ' + stamp + ' */\n'
  + densityBlock(':root', 'normal') + '\n'
  + densityBlock(':root[data-density="compact"]', 'compact') + '\n'
  + densityBlock(':root[data-density="relaxed"]', 'relaxed') + '\n';

const fallback = data.palettes[data.default];
if (!fallback) throw new Error('附录 A default 指向不存在的配色: ' + data.default);
const fallbackCss = ['light', 'dark']
  .map(mode => cssBlock(mode, null, Rules.deriveVars(baseOf(fallback, mode), mode, data.derivation[mode])));

const palettesCss = '/* ' + stamp + ' */\n'
  + '/* 默认回退块 = ' + data.default + '；具体配色块以更高优先级覆盖（规则 §2/§3/§4）。 */\n'
  + fallbackCss.join('\n') + '\n' + paletteCss.join('\n') + '\n';

const palettesJs = '// ' + stamp + '\n'
  + 'window.VexPalettes = ' + JSON.stringify(paletteEntries, null, 2) + ';\n'
  + 'window.VexPaletteKey = key => (' + JSON.stringify(legacyAliases) + ')[key] || key;\n';

const rulesDataJs = '// ' + stamp + '\n'
  + 'window.VexPaletteRulesData = ' + JSON.stringify({
    ruleVersion: data.ruleVersion, source: 'CodeWF.Avalonia ' + version,
    derivation: data.derivation, statusDefaults: data.statusDefaults,
    density: data.density, markdownSizeTiers: data.markdownSizeTiers,
    default: data.default, palettes: data.palettes
  }, null, 2) + ';\n';

if (issues.length) {
  console.error('对比度校验未通过（规则 §5）：');
  issues.forEach(message => console.error('  ✗ ' + message));
  process.exitCode = 1;
  if (!args.includes('--force')) { console.error('已阻止落盘；调整附录 A 取值或加 --force 强制生成。'); process.exit(1); }
} else {
  console.log('对比度校验通过：' + Object.keys(data.palettes).length + ' 套 × 明暗。');
}

if (flag('--check') >= 0) { console.log('--check：只校验，未写文件。'); process.exit(process.exitCode || 0); }

function write(file, value) {
  const target = path.join(root, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== value) {
    fs.writeFileSync(target, value, 'utf8');
    console.log('已生成 ' + file);
  } else {
    console.log('未变化 ' + file);
  }
}
write('assets/palettes.css', palettesCss);
write('assets/palettes.js', palettesJs);
write('assets/density.css', densityCss);
write('assets/generated/palette-rules-data.js', rulesDataJs);
console.log('默认配色: ' + data.default + ' · 版本戳: CodeWF.Avalonia ' + version);
