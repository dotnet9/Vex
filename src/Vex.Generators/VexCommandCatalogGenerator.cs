using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Vex.Generators;

/// <summary>
/// 命令目录生成器：编译期收集 [VexCommand] 标注的 ShellActionKind / EditorActionKind
/// 枚举成员，产出 VexCommandCatalog.Items 静态表供命令面板消费（AOT 安全，无运行时反射）。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class VexCommandCatalogGenerator : IIncrementalGenerator
{
    private const string AttributeFqn = "Vex.Core.Messaging.VexCommandAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entries = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeFqn,
            predicate: static (node, _) => node is EnumMemberDeclarationSyntax,
            transform: static (ctx, _) => Transform(ctx));

        context.RegisterSourceOutput(entries.Collect(), static (spc, all) =>
        {
            var ordered = all
                .Distinct()
                .OrderBy(entry => entry.OrderKey, System.StringComparer.Ordinal)
                .ToList();

            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated> 由 VexCommandCatalogGenerator 生成，请勿手改。 </auto-generated>");
            builder.AppendLine("namespace Vex.Core.Messaging;");
            builder.AppendLine();
            builder.AppendLine("/// <summary>命令面板目录：编译期从 [VexCommand] 标注收集（分组/标签/快捷键/动作）。</summary>");
            builder.AppendLine("public static class VexCommandCatalog");
            builder.AppendLine("{");
            builder.AppendLine("    public static System.Collections.Generic.IReadOnlyList<VexCommandEntry> Items { get; } = new VexCommandEntry[]");
            builder.AppendLine("    {");
            foreach (var entry in ordered)
            {
                builder.Append("        new(");
                builder.Append(SyntaxFactory.Literal(entry.Group).ToFullString());
                builder.Append(", ");
                builder.Append(SyntaxFactory.Literal(entry.Label).ToFullString());
                builder.Append(", ");
                builder.Append(SyntaxFactory.Literal(entry.Gesture).ToFullString());
                builder.Append(", ");
                builder.Append(entry.Action);
                builder.AppendLine("),");
            }
            builder.AppendLine("    };");
            builder.AppendLine("}");
            builder.AppendLine();
            builder.AppendLine("public sealed record VexCommandEntry(string Group, string Label, string Gesture, Enum Action);");
            spc.AddSource("VexCommandCatalog.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
        });
    }

    private static Entry Transform(GeneratorAttributeSyntaxContext context)
    {
        var member = (EnumMemberDeclarationSyntax)context.TargetNode;
        var enumSymbol = (INamedTypeSymbol)context.TargetSymbol;
        var action = enumSymbol.ToDisplayString() + "." + member.Identifier.Text;

        var attribute = context.Attributes[0];
        var group = attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is string g ? g : string.Empty;
        var label = attribute.ConstructorArguments.Length > 1 && attribute.ConstructorArguments[1].Value is string l ? l : member.Identifier.Text;
        var gesture = string.Empty;
        foreach (var pair in attribute.NamedArguments)
        {
            if (pair.Key == "Gesture" && pair.Value.Value is string gestureValue)
            {
                gesture = gestureValue;
            }
        }

        // 排序键：枚举声明顺序（KeepAnnotationCount）保证目录顺序与枚举一致。
        var order = member.Identifier.Text;
        return new Entry(group, label, gesture, action, order);
    }

    private sealed record Entry(string Group, string Label, string Gesture, string Action, string OrderKey);
}
