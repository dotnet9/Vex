// Each SVG path starts at its own origin; concatenation must not inherit the previous path's endpoint.
function independentPath(data) {
  const number = '[-+]?(?:\\d*\\.\\d+|\\d+\\.?\\d*)(?:[eE][-+]?\\d+)?';
  const initialMove = new RegExp(`^\\s*m\\s*(${number})[\\s,]*(${number})([\\s\\S]*)$`).exec(data);
  if (!initialMove) return data;
  const [, x, y, remaining] = initialMove;
  const tail = remaining.replace(/^[\s,]+/, '');
  // Additional coordinates after a relative moveto are relative lineto commands.
  return `M${x} ${y}${tail ? (/^[a-z]/i.test(tail) ? ` ${tail}` : `l${tail}`) : ''}`;
}

function geometry(name) {
  const svg = fs.readFileSync(path.join(source, `${name}.svg`), 'utf8');
  if (!svg.includes('viewBox="0 0 24 24"') || /<(?:g|use|ellipse|polygon|defs)\b|\b(?:transform|style)=/.test(svg))
    throw new Error(`Unsupported SVG: ${name}`);
  const result = [];
  for (const [, tag, text] of svg.matchAll(/<(\w+)\b([^>]*?)\/?\s*>/g)) {
    if (tag === 'svg') continue;
    const attributes = Object.fromEntries([...text.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
    if (attributes.fill && attributes.fill !== 'none') throw new Error(`Unsupported fill: ${name}`);
    const n = key => Number(attributes[key] ?? 0);
    if (tag === 'path') result.push(independentPath(attributes.d));
    else if (tag === 'line') result.push(`M${n('x1')} ${n('y1')}L${n('x2')} ${n('y2')}`);
    else if (tag === 'polyline') result.push(`M${attributes.points}`);
    else if (tag === 'circle') {
      const x = n('cx'), y = n('cy'), r = n('r');
      result.push(`M${x-r} ${y}a${r} ${r} 0 1 0 ${2*r} 0a${r} ${r} 0 1 0 ${-2*r} 0`);
    } else if (tag === 'rect') {
      const x = n('x'), y = n('y'), w = n('width'), h = n('height');
      const rx = Math.min(Number(attributes.rx ?? attributes.ry ?? 0), w/2);
      const ry = Math.min(Number(attributes.ry ?? attributes.rx ?? 0), h/2);
      result.push(rx && ry
        ? `M${x+rx} ${y}H${x+w-rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}V${y+h-ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}H${x+rx}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}V${y+ry}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`
        : `M${x} ${y}h${w}v${h}h${-w}z`);
    } else throw new Error(`Unsupported element ${tag}: ${name}`);
  }
  if (!result.length) throw new Error(`Empty geometry: ${name}`);
  return result.join(' ');
}

module.exports = { independentPath, geometry };

if (require.main === module) {
  const entries = names.map(name => `        ["${name}"] = ${JSON.stringify(geometry(name))},`);
  const generated = `// <auto-generated />\n// Lucide 0.468.0, f12b0de177fbc2a6795e99be065887e72b237123.\n// Generated by scripts/generate-menu-icon-geometry.cjs.\nnamespace Vex.Controls;\n\ninternal static class MenuIconGeometry\n{\n    internal static readonly IReadOnlyDictionary<string, string> Data = new Dictionary<string, string>(StringComparer.Ordinal)\n    {\n${entries.join('\n')}\n    };\n}\n`;
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) throw new Error('Menu icon geometry is out of date');
    console.log(`Verified ${names.length} Lucide menu geometries`);
  } else {
    fs.writeFileSync(output, generated);
    console.log(`Generated ${names.length} Lucide menu geometries`);
  }
}
